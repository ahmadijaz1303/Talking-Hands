#!/usr/bin/env python
# -*- coding: utf-8 -*-
# Ye file digit hand signs ko webcam se detect karti hai.
# Flow simple hai:
# frame lo -> hand landmarks nikalo -> landmarks normalize karo ->
# trained model ko do -> predicted digit screen par dikhao.
import csv
import copy
import argparse
import itertools
import time

import cv2 as cv
import numpy as np
import mediapipe as mp

from utils import CvFpsCalc
from model.keypoint_classifier.keypoint_classifier import KeyPointClassifier


def get_args():
    # Yahan se run-time settings milti hain.
    # Agar user camera number ya width/height change karna chahe
    # to command line se ye values pass kar sakta hai.
    parser = argparse.ArgumentParser()

    parser.add_argument("--device", type=int, default=0)
    parser.add_argument("--width", help='cap width', type=int, default=960)
    parser.add_argument("--height", help='cap height', type=int, default=540)

    parser.add_argument('--use_static_image_mode', action='store_true')
    parser.add_argument("--min_detection_confidence",
                        help='min_detection_confidence',
                        type=float,
                        default=0.7)
    parser.add_argument("--min_tracking_confidence",
                        help='min_tracking_confidence',
                        type=int,
                        default=0.5)

    args = parser.parse_args()

    return args


def main():
    # Sab se pehle user ki settings read karte hain.
    args = get_args()

    cap_device = args.device
    cap_width = args.width
    cap_height = args.height

    use_static_image_mode = args.use_static_image_mode
    min_detection_confidence = args.min_detection_confidence
    min_tracking_confidence = args.min_tracking_confidence

    use_brect = True

    # Webcam open karte hain aur desired frame size set karte hain.
    cap = cv.VideoCapture(cap_device)
    cap.set(cv.CAP_PROP_FRAME_WIDTH, cap_width)
    cap.set(cv.CAP_PROP_FRAME_HEIGHT, cap_height)

    # MediaPipe Hands hand ke 21 landmarks nikalne ke liye use hota hai.
    mp_hands = mp.solutions.hands
    hands = mp_hands.Hands(
        static_image_mode=use_static_image_mode,
        max_num_hands=1,
        min_detection_confidence=min_detection_confidence,
        min_tracking_confidence=min_tracking_confidence,
    )

    # Ye hamara digit model loader hai.
    # Is ka default model path digit wali .tflite file hota hai.
    keypoint_classifier = KeyPointClassifier()

    # Label file me class id ka actual naam hota hai.
    # Misal ke tor par 0 -> 1, 1 -> 2, ... 9 -> 10
    with open('model/keypoint_classifier/keypoint_classifier_label.csv',
              encoding='utf-8-sig') as f:
        keypoint_classifier_labels = csv.reader(f)
        keypoint_classifier_labels = [
            row[0] for row in keypoint_classifier_labels
        ]

    # FPS sirf screen par speed show karne ke liye.
    cvFpsCalc = CvFpsCalc(buffer_len=10)
    target_fps = 30
    frame_interval = 1.0 / target_fps

    # mode 0 = normal prediction
    # mode 1 = keypoint logging / dataset banana
    mode = 0

    while True:
        loop_start = time.perf_counter()

        # Har frame me FPS update hota hai.
        fps = cvFpsCalc.get()

        # Keyboard input yahan handle hota hai.
        # ESC dabane se app band ho jati hai.
        key = cv.waitKey(1)
        if key == 27:  # ESC
            break
        # number selected class id hoti hai.
        # mode batata hai ke normal chalna hai ya logging karni hai.
        number, mode = select_mode(key, mode)

        # Webcam se next frame lo.
        ret, image = cap.read()
        if not ret:
            break
        # Mirror karne se user ko selfie type natural view milta hai.
        image = cv.flip(image, 1)  # Mirror display
        # Drawing ke liye alag copy banao taake original frame safe rahe.
        debug_image = copy.deepcopy(image)

        # MediaPipe RGB image expect karta hai.
        image = cv.cvtColor(image, cv.COLOR_BGR2RGB)

        image.flags.writeable = False
        results = hands.process(image)
        image.flags.writeable = True

        # Agar hand detect ho gaya to us ke landmarks process karo.
        if results.multi_hand_landmarks is not None:
            for hand_landmarks, handedness in zip(results.multi_hand_landmarks,
                                                  results.multi_handedness):
                # Hand ke around rectangle nikalte hain.
                brect = calc_bounding_rect(debug_image, hand_landmarks)
                # 21 landmarks ki x,y list banao.
                landmark_list = calc_landmark_list(debug_image, hand_landmarks)

                # Landmarks ko model input format me convert karo.
                # Relative + normalized values model ko zyada stable input deti hain.
                pre_processed_landmark_list = pre_process_landmark(
                    landmark_list)
                # Agar logging mode on hai to current sample CSV me save ho jata hai.
                logging_csv(number, mode, pre_processed_landmark_list)

                # Ab processed landmarks model ko do aur class id lo.
                hand_sign_id = keypoint_classifier(pre_processed_landmark_list)

                # Ab screen par sab cheezen draw karo.
                debug_image = draw_bounding_rect(use_brect, debug_image, brect)
                debug_image = draw_landmarks(debug_image, landmark_list)
                debug_image = draw_info_text(
                    debug_image,
                    brect,
                    handedness,
                    keypoint_classifier_labels[hand_sign_id],
                )

        debug_image = draw_info(debug_image, fps, mode, number)

        # Final frame user ko show karo.
        cv.imshow('Hand Gesture Recognition', debug_image)

        elapsed = time.perf_counter() - loop_start
        if elapsed < frame_interval:
            time.sleep(frame_interval - elapsed)

    # Program close hote waqt webcam aur windows free karo.
    cap.release()
    cv.destroyAllWindows()


def select_mode(key, mode):
    # Start me assume karo ke koi class select nahin hui.
    number = -1
    # Digit dataset ke liye key mapping:
    # '1' key -> class id 0
    # '2' key -> class id 1
    # ...
    # '9' key -> class id 8
    # '0' key -> class id 9
    if 48 <= key <= 57:  # 0 ~ 9
        number = key - 48
        if number == 0:
            number = 9  # Map '0' key to label ID 9 (Label "10")
        else:
            number = number - 1  # Map keys '1'-'9' to IDs 0-8 (Labels "1"-"9")
    # n se normal mode aur k se keypoint logging mode.
    if key == 110:  # n
        mode = 0
    if key == 107:  # k
        mode = 1
    return number, mode


def calc_bounding_rect(image, landmarks):
    # Ye function landmarks ka outer rectangle nikalta hai.
    image_width, image_height = image.shape[1], image.shape[0]

    landmark_array = np.empty((0, 2), int)

    for _, landmark in enumerate(landmarks.landmark):
        landmark_x = min(int(landmark.x * image_width), image_width - 1)
        landmark_y = min(int(landmark.y * image_height), image_height - 1)

        landmark_point = [np.array((landmark_x, landmark_y))]

        landmark_array = np.append(landmark_array, landmark_point, axis=0)

    x, y, w, h = cv.boundingRect(landmark_array)

    return [x, y, x + w, y + h]


def calc_landmark_list(image, landmarks):
    # MediaPipe normalized points deta hai.
    # Hum unko image ke pixel coordinates me badal rahe hain.
    image_width, image_height = image.shape[1], image.shape[0]

    landmark_point = []

    # Keypoint
    for _, landmark in enumerate(landmarks.landmark):
        landmark_x = min(int(landmark.x * image_width), image_width - 1)
        landmark_y = min(int(landmark.y * image_height), image_height - 1)
        # landmark_z = landmark.z

        landmark_point.append([landmark_x, landmark_y])

    return landmark_point


def pre_process_landmark(landmark_list):
    # Ye function model ke liye features banata hai.
    # Is ke bina raw landmarks directly use nahin hote.
    temp_landmark_list = copy.deepcopy(landmark_list)

    # Landmark 0 ko base point bana kar sab ko relative karo.
    # Is se hand ki screen par position ka effect kam hota hai.
    base_x, base_y = 0, 0
    for index, landmark_point in enumerate(temp_landmark_list):
        if index == 0:
            base_x, base_y = landmark_point[0], landmark_point[1]

        temp_landmark_list[index][0] = temp_landmark_list[index][0] - base_x
        temp_landmark_list[index][1] = temp_landmark_list[index][1] - base_y

    # 21 (x, y) pairs ko 42-length flat feature vector me badal do.
    temp_landmark_list = list(
        itertools.chain.from_iterable(temp_landmark_list))

    # Normalize karo taake hand size aur camera distance ka effect kam ho.
    max_value = max(list(map(abs, temp_landmark_list)))

    def normalize_(n):
        return n / max_value

    temp_landmark_list = list(map(normalize_, temp_landmark_list))

    return temp_landmark_list


def logging_csv(number, mode, landmark_list):
    # mode 0 me kuch save nahin hota.
    if mode == 0:
        pass
    # mode 1 me row append hoti hai.
    # Row format:
    # [label_id, x0, y0, x1, y1, ... x20, y20]
    if mode == 1 and (0 <= number <= 9):
        csv_path = 'model/keypoint_classifier/keypoint.csv'
        with open(csv_path, 'a', newline="") as f:
            writer = csv.writer(f)
            writer.writerow([number, *landmark_list])
    return


